CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS technician (
  technician_id BIGINT PRIMARY KEY,
  technician_code VARCHAR(5) NOT NULL UNIQUE
    CHECK (technician_code ~ '^KT[0-9]{3}$'),
  full_name VARCHAR(120) NOT NULL,
  center_code VARCHAR(10) NOT NULL
    CHECK (center_code ~ '^TT[0-9]{2}$'),
  level VARCHAR(20) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ticket (
  ticket_id BIGINT PRIMARY KEY,
  ticket_code VARCHAR(24) NOT NULL UNIQUE
    CHECK (ticket_code ~ '^BH-[0-9]{6}/[0-9]{4}$'),
  customer_id BIGINT NOT NULL,
  product_id INTEGER NOT NULL,
  serial_no VARCHAR(50) NOT NULL,
  center_code VARCHAR(10) NOT NULL
    CHECK (center_code ~ '^TT[0-9]{2}$'),
  category_name VARCHAR(60) NOT NULL CHECK (category_name IN (
    'MAN_HINH', 'PIN', 'SAC', 'PHAN_MEM', 'NUOC_VAO', 'KHAC'
  )),
  priority VARCHAR(12) NOT NULL
    CHECK (priority IN ('CAO', 'TRUNG_BINH', 'THAP')),
  status VARCHAR(20) NOT NULL DEFAULT 'MOI'
    CHECK (status IN (
      'MOI', 'DA_PHAN_CONG', 'DANG_XU_LY', 'CHO_LINH_KIEN', 'HOAN_TAT', 'DA_DONG'
    )),
  issue_desc TEXT,
  received_at TIMESTAMPTZ NOT NULL,
  due_date TIMESTAMPTZ NOT NULL,
  closed_at TIMESTAMPTZ,
  is_warranty BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT chk_ticket_due_after_received CHECK (due_date >= received_at),
  CONSTRAINT chk_ticket_closed_after_received
    CHECK (closed_at IS NULL OR closed_at >= received_at)
);

CREATE TABLE IF NOT EXISTS technician_skill (
  technician_id BIGINT NOT NULL REFERENCES technician(technician_id),
  category_name VARCHAR(60) NOT NULL CHECK (category_name IN (
    'MAN_HINH', 'PIN', 'SAC', 'PHAN_MEM', 'NUOC_VAO', 'KHAC'
  )),
  proficiency SMALLINT NOT NULL CHECK (proficiency BETWEEN 1 AND 5),
  PRIMARY KEY (technician_id, category_name)
);

CREATE TABLE IF NOT EXISTS ticket_assignment (
  assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL REFERENCES ticket(ticket_id),
  technician_id BIGINT NOT NULL REFERENCES technician(technician_id),
  assigned_by VARCHAR(100) NOT NULL,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ended_at TIMESTAMPTZ,
  reason VARCHAR(255),
  CONSTRAINT chk_assignment_end_after_start
    CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);

CREATE TABLE IF NOT EXISTS appointment (
  appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL REFERENCES ticket(ticket_id),
  technician_id BIGINT NOT NULL REFERENCES technician(technician_id),
  center_code VARCHAR(10) NOT NULL
    CHECK (center_code ~ '^TT[0-9]{2}$'),
  appointment_type VARCHAR(30) NOT NULL
    CHECK (appointment_type IN ('GIAO_MAY', 'NHAN_MAY', 'KIEM_TRA_TAI_CHO')),
  start_at TIMESTAMPTZ NOT NULL,
  end_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'DA_DAT'
    CHECK (status IN ('DA_DAT', 'DA_XAC_NHAN', 'HOAN_TAT', 'KHACH_HUY', 'KHACH_KHONG_DEN')),
  note VARCHAR(255),
  CONSTRAINT chk_appointment_time CHECK (end_at > start_at),
  CONSTRAINT chk_appointment_duration CHECK (
    end_at - start_at BETWEEN INTERVAL '15 minutes' AND INTERVAL '240 minutes'
  ),
  CONSTRAINT ex_appointment_no_overlap
    EXCLUDE USING gist (
      technician_id WITH =,
      tstzrange(start_at, end_at, '[)') WITH &&
    )
    WHERE (status IN ('DA_DAT', 'DA_XAC_NHAN'))
);

CREATE TABLE IF NOT EXISTS ticket_status_log (
  log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL REFERENCES ticket(ticket_id),
  from_status VARCHAR(20)
    CHECK (from_status IS NULL OR from_status IN (
      'MOI', 'DA_PHAN_CONG', 'DANG_XU_LY', 'CHO_LINH_KIEN', 'HOAN_TAT', 'DA_DONG'
    )),
  to_status VARCHAR(20) NOT NULL CHECK (to_status IN (
    'MOI', 'DA_PHAN_CONG', 'DANG_XU_LY', 'CHO_LINH_KIEN', 'HOAN_TAT', 'DA_DONG'
  )),
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  changed_by VARCHAR(100) NOT NULL,
  note VARCHAR(255)
);
